"""Write the third-party notices for the Qt modules bundled with NumeriPlot.

Reads Qt's qt_attribution.json records and the license texts they reference
from the official source archives (see tools/fetch_release_sources.py) and
prints one plain-text notice file.

Usage:
  python tools/qt_attributions.py QTBASE.tar.xz QTSVG.tar.xz > licenses/Qt-6.10.2-third-party.txt
"""
import json
import posixpath
import re
import sys
import tarfile

# Records for code that never reaches the macOS app: build and test tooling,
# and the integrations of other platforms. Everything else is kept, so the
# notices may list more than the bundle contains, never less.
SKIPPED = (
    "cmake/", "util/", "src/testlib/", "src/testinternal/",
    "src/3rdparty/android", "src/3rdparty/gradle", "src/3rdparty/wasm",
    "src/3rdparty/wintab", "src/3rdparty/xcb", "src/3rdparty/wayland",
    "src/3rdparty/D3D12MemoryAllocator",
)
SPDX_TOKEN = re.compile(r"[A-Za-z0-9.+-]+")
RULE = "-" * 72


def read_members(path, wanted):
    """Text of archive members whose path inside the module satisfies wanted()."""
    texts = {}
    with tarfile.open(path, "r:xz") as archive:
        for member in archive:
            top, _, rel = member.name.partition("/")
            if member.isfile() and wanted(rel):
                texts[rel] = archive.extractfile(member).read().decode("utf-8", "replace")
    return top, texts


def as_list(value):
    if not value:
        return []
    return value if isinstance(value, list) else [value]


def module_records(path):
    top, jsons = read_members(path, lambda rel: rel.endswith("qt_attribution.json"))
    records = []
    for rel, text in sorted(jsons.items()):
        folder = posixpath.dirname(rel)
        if folder.startswith(SKIPPED) or rel.startswith(SKIPPED):
            continue
        data = json.loads(text, strict=False)
        for record in as_list(data):
            records.append((folder, record))
    needed = set()
    for folder, record in records:
        for name in as_list(record.get("LicenseFiles")) + as_list(record.get("LicenseFile")):
            needed.add(posixpath.normpath(posixpath.join(folder, name)))
        if record.get("CopyrightFile"):
            needed.add(posixpath.normpath(posixpath.join(folder, record["CopyrightFile"])))
    _, texts = read_members(path, lambda rel: rel in needed or rel.startswith("LICENSES/"))
    module, _, version = top.partition("-everywhere-src-")
    return module, version, records, texts


def main(argv):
    if len(argv) < 2:
        raise SystemExit(__doc__)
    sections, spdx_texts, used_ids, version = [], {}, set(), ""
    for archive in argv[1:]:
        module, version, records, texts = module_records(archive)
        spdx_texts.update({posixpath.basename(rel)[:-4]: text for rel, text in texts.items()
                           if rel.startswith("LICENSES/") and rel.endswith(".txt")})
        for folder, record in sorted(records, key=lambda item: item[1].get("Name", "").lower()):
            lines = [RULE, f"{record.get('Name', record.get('Id', '?'))} {record.get('Version', '')}".rstrip(),
                     f"Qt module: {module} ({folder})"]
            if record.get("QtUsage"):
                lines.append(f"Used: {' '.join(str(record['QtUsage']).split())}")
            license_id = record.get("LicenseId", "")
            lines.append(f"License: {record.get('License', '')} ({license_id})")
            for holder in as_list(record.get("Copyright")):
                lines.append(f"Copyright: {holder}")
            files = as_list(record.get("LicenseFiles")) + as_list(record.get("LicenseFile"))
            if record.get("CopyrightFile"):
                files.append(record["CopyrightFile"])
            for name in files:
                text = texts.get(posixpath.normpath(posixpath.join(folder, name)))
                if text:
                    lines += ["", text.strip()]
            if not files:
                ids = [token for token in SPDX_TOKEN.findall(license_id)
                       if token not in {"AND", "OR", "WITH"}]
                used_ids.update(ids)
                if ids:
                    lines.append(f"License text: {', '.join(ids)} (appendix below)")
            sections.append("\n".join(lines))
    print(f"Qt {version} — third-party notices for the bundled Qt modules")
    print(f"(qtbase, qtsvg; generated by tools/qt_attributions.py from the official sources)\n")
    print("Qt itself is used under the GNU LGPL v3 (licenses/LGPL-3.0-only.txt) with the")
    print("GNU GPL v3 (LICENSE). Its source code is published with each NumeriPlot release.\n")
    print("\n\n".join(sections))
    print(f"\n{RULE}\nAppendix: license texts referenced above by SPDX identifier\n{RULE}")
    for license_id in sorted(used_ids):
        text = spdx_texts.get(license_id)
        if text:
            print(f"\n=== {license_id} ===\n\n{text.strip()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
